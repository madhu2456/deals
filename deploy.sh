#!/bin/bash
# =============================================================================
# Deals — server bootstrap + non-root updates (user: madhu)
#
# First-time bootstrap (once, as root):
#   export DEPLOY_USER=madhu
#   git clone https://github.com/madhu2456/deals.git /opt/deals
#   cd /opt/deals && chmod +x deploy.sh docker/entrypoint.sh
#   sudo ./deploy.sh
#
# Updates as madhu (GitHub Actions):
#   cd /opt/deals && ./deploy.sh --update
#
# Backup cron (non-root, as madhu; idempotent):
#   cd /opt/deals && ./deploy.sh --install-backup-cron
# =============================================================================

set -euo pipefail

APP_NAME="deals"
DEPLOY_USER="${DEPLOY_USER:-madhu}"
REPO_URL="${REPO_URL:-https://github.com/madhu2456/deals.git}"
BRANCH="${BRANCH:-main}"
DOMAIN="${DOMAIN:-deals.madhudadi.in}"
# HOST port only (container still uses 3000 internally).
# madhudadi.in = 3000, blog = 3001, deals = 3002, enroller = 8000
APP_PORT="${APP_PORT:-3002}"
APP_DIR="${APP_DIR:-/opt/deals}"

MODE="bootstrap"
if [ "${1:-}" = "--update" ] || [ "${1:-}" = "update" ]; then
  MODE="update"
elif [ "${1:-}" = "--install-backup-cron" ] || [ "${1:-}" = "install-backup-cron" ]; then
  MODE="install-backup-cron"
fi

echo "=== Deals deployment (${MODE}) ==="
echo "    APP_DIR=${APP_DIR}"
echo "    DOMAIN=${DOMAIN}"
echo "    BRANCH=${BRANCH}"
echo "    USER=$(whoami) (target deploy user: ${DEPLOY_USER})"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
need_root() {
  if [ "$(id -u)" -ne 0 ]; then
    echo "Bootstrap requires root once. Run: sudo $0"
    exit 1
  fi
}

need_docker() {
  if ! command -v docker >/dev/null 2>&1; then
    echo "Docker is not installed. Run full bootstrap as root first: sudo ./deploy.sh"
    exit 1
  fi
  if ! docker info >/dev/null 2>&1; then
    echo "Cannot talk to Docker as $(whoami)."
    echo "Add user to docker group (as root):"
    echo "  usermod -aG docker ${DEPLOY_USER}"
    echo "  # then log out/in, or: newgrp docker"
    exit 1
  fi
  if ! docker compose version >/dev/null 2>&1; then
    echo "docker compose plugin missing. Install as root: apt-get install -y docker-compose-plugin"
    exit 1
  fi
}

install_docker() {
  if ! command -v docker &>/dev/null; then
    echo "Installing Docker..."
    curl -fsSL https://get.docker.com -o /tmp/get-docker.sh
    sh /tmp/get-docker.sh
    rm -f /tmp/get-docker.sh
    systemctl enable --now docker
  else
    echo "Docker already installed."
  fi

  if ! docker compose version &>/dev/null; then
    echo "Installing Docker Compose plugin..."
    apt-get update -y
    apt-get install -y docker-compose-plugin
  fi
}

ensure_deploy_user() {
  if ! id "${DEPLOY_USER}" >/dev/null 2>&1; then
    echo "Creating user ${DEPLOY_USER}..."
    useradd -m -s /bin/bash "${DEPLOY_USER}"
  fi
  usermod -aG docker "${DEPLOY_USER}" || true
  # Passwordless docker is via group membership (not sudo)
  echo "User ${DEPLOY_USER} is in docker group."
}

ensure_env() {
  if [ ! -f "${APP_DIR}/.env" ]; then
    echo "Creating .env with secure defaults..."
    ADMIN_SECRET="$(openssl rand -hex 32)"
    ADMIN_PASSWORD="$(openssl rand -hex 12)"
    cat >"${APP_DIR}/.env" <<EOF
# Generated by deploy.sh — change ADMIN_* after first login
DATABASE_URL="file:/app/data/deals.db"
ADMIN_USERNAME="admin"
ADMIN_PASSWORD="${ADMIN_PASSWORD}"
ADMIN_SECRET="${ADMIN_SECRET}"
NEXT_PUBLIC_SITE_URL="https://${DOMAIN}"
APP_PORT=${APP_PORT}
# Empty disables GTM. Compose interpolates this as a build arg (Next inlines
# NEXT_PUBLIC_* at image build). Set the container ID on the host to enable.
NEXT_PUBLIC_GTM_ID=
# First-time provisioning only: flipped to false after the first container
# start (see flip_seed_flag). Routine --update deploys never re-enable seeding.
RUN_SEED=true
NODE_ENV=production
EOF
    chmod 600 "${APP_DIR}/.env"
    if id "${DEPLOY_USER}" >/dev/null 2>&1; then
      chown "${DEPLOY_USER}:${DEPLOY_USER}" "${APP_DIR}/.env" 2>/dev/null || true
    fi
    echo "  .env written. Initial admin password: ${ADMIN_PASSWORD}"
    echo "  (also saved in ${APP_DIR}/.env — rotate after first login)"
  else
    echo ".env already exists — ensuring APP_PORT=${APP_PORT}"
    if grep -q '^APP_PORT=' "${APP_DIR}/.env" 2>/dev/null; then
      sed -i "s/^APP_PORT=.*/APP_PORT=${APP_PORT}/" "${APP_DIR}/.env"
    else
      echo "APP_PORT=${APP_PORT}" >>"${APP_DIR}/.env"
    fi
    # Placeholder only when missing — never overwrite a host-set container ID.
    if ! grep -q '^NEXT_PUBLIC_GTM_ID=' "${APP_DIR}/.env" 2>/dev/null; then
      echo "NEXT_PUBLIC_GTM_ID=" >>"${APP_DIR}/.env"
    fi
  fi
}

# Seed only on first-time provisioning. The container bakes RUN_SEED from
# .env at `docker compose up` (container-create) time, so flipping the host
# .env right after `up` does not affect the just-started container — it seeds
# once — but every later recreate/restart via compose sees RUN_SEED=false and
# skips seeding. The flip therefore never re-enables seeding on routine
# --update deploys (which never write RUN_SEED=true; ensure_env only writes it
# when .env is created from scratch).
flip_seed_flag() {
  local env_file="${1:-${APP_DIR}/.env}"
  if [ -f "${env_file}" ] && grep -q '^RUN_SEED=true' "${env_file}" 2>/dev/null; then
    sed -i 's/^RUN_SEED=true/RUN_SEED=false/' "${env_file}" || true
    echo "  RUN_SEED set to false for future restarts."
  fi
}

# Run a command as root if needed (root, or passwordless sudo)
as_root() {
  if [ "$(id -u)" -eq 0 ]; then
    "$@"
  elif command -v sudo >/dev/null 2>&1 && sudo -n true 2>/dev/null; then
    sudo "$@"
  else
    return 1
  fi
}

# Idempotent host crontab for SQLite backup + freshness (F-DEAL-004).
# Re-runs replace the marked entries instead of duplicating them. Uses the
# documented production layout: backups in /var/backups/deals (the same
# default verify_backup_freshness.sh watches), logs in /var/log/deals-backup.log.
# Deployment-type detection: when docker-compose.yml mounts the named volume
# deals_data:/app/data, the live DB is unreachable from the host, so the
# container (docker compose exec) variants are installed — the scripts run
# inside the deals container against /app/data (DB + backups land in the
# volume). Bind-mount deployments keep the host entries (DB at
# /opt/deals/data/deals.db). Override with BACKUP_DATABASE_URL to force a
# host path explicitly (bind-mounted deployments only — see docs/ops/backup-restore.md).
install_backup_cron() {
  local backup_dir="${BACKUP_DIR:-/var/backups/deals}"
  local db_url="${BACKUP_DATABASE_URL:-file:/opt/deals/data/deals.db}"
  local compose_file="${APP_DIR}/docker-compose.yml"
  local use_exec_variant=0

  if ! command -v crontab >/dev/null 2>&1; then
    echo "ERROR: crontab not found. Install cron first: apt-get install -y cron"
    exit 1
  fi

  # Named-volume deployment? An explicit BACKUP_DATABASE_URL wins (operator
  # knows the DB is host-reachable), so only auto-detect when it is unset.
  if [ -z "${BACKUP_DATABASE_URL:-}" ] && [ -f "${compose_file}" ] \
    && grep -q 'deals_data:/app/data' "${compose_file}"; then
    use_exec_variant=1
    echo "  Deployment detected: named volume deals_data:/app/data — installing container (exec) cron entries."
  elif [ -f "${compose_file}" ] && grep -q 'deals_data:/app/data' "${compose_file}"; then
    echo "WARNING: docker-compose.yml mounts named volume deals_data:/app/data but BACKUP_DATABASE_URL is set."
    echo "  The host cron will read ${db_url} — only correct if that path is a real"
    echo "  host file (bind mount); otherwise backups will miss the live DB."
  fi

  if [ "${use_exec_variant}" -eq 0 ] && ! command -v sqlite3 >/dev/null 2>&1; then
    echo "WARNING: sqlite3 CLI missing on host — the daily backup entry will fail."
    echo "  Install once: sudo apt-get install -y sqlite3"
  fi

  # Ensure the host backup dir exists (root/sudo needed once under
  # /var/backups). Container (exec) entries write the named volume directly;
  # the host dir only matters for the host variant + the rclone offsite copy.
  if [ "${use_exec_variant}" -eq 0 ]; then
    if ! as_root mkdir -p "${backup_dir}"; then
      echo "WARNING: cannot create ${backup_dir} (need root or passwordless sudo)."
      echo "  Run once: sudo mkdir -p ${backup_dir} && sudo chown ${DEPLOY_USER}:${DEPLOY_USER} ${backup_dir}"
    else
      as_root chown "${DEPLOY_USER}:${DEPLOY_USER}" "${backup_dir}" 2>/dev/null || true
      as_root chmod 700 "${backup_dir}" 2>/dev/null || true
    fi

    # Warn when the DB is not reachable from the host (named-volume deploys
    # are handled above via the exec variant).
    local db_path="${db_url#file:}"
    if [ ! -f "${db_path}" ]; then
      echo "WARNING: database not found at ${db_path}."
      echo "  If /app/data is a named Docker volume (docker-compose.yml), re-run"
      echo "  WITHOUT BACKUP_DATABASE_URL so the container (exec) entries are installed,"
      echo "  or bind-mount /app/data to a host path (recommended)."
    fi
  else
    echo "  Backups land in /app/data/backups (inside the named volume)."
    echo "  Copy files out for offsite/restore work, e.g.: docker cp deals-app:/app/data/backups/<file> ."
  fi

  # Idempotent rewrite: drop previous deals-backup entries, keep the rest.
  local tmp
  tmp="$(mktemp)"
  if ! crontab -l 2>/dev/null | grep -v -e 'deals-sqlite-backup' -e 'deals-backup-freshness' -e 'backup-sqlite.sh' -e 'verify_backup_freshness.sh' >"${tmp}"; then
    : >"${tmp}"
  fi
  if [ "${use_exec_variant}" -eq 1 ]; then
    cat >>"${tmp}" <<EOF
# deals-sqlite-backup (deploy.sh --install-backup-cron; daily 03:15 UTC; container exec)
15 3 * * * cd ${APP_DIR} && docker compose exec -T deals sh -c 'DATABASE_URL=file:/app/data/deals.db BACKUP_DIR=/app/data/backups /app/scripts/backup-sqlite.sh' >>/var/log/deals-backup.log 2>&1
# deals-backup-freshness (deploy.sh --install-backup-cron; daily 03:45 UTC; container exec)
45 3 * * * cd ${APP_DIR} && docker compose exec -T deals sh -c 'BACKUP_DIR=/app/data/backups MAX_AGE_HOURS=26 /app/scripts/verify_backup_freshness.sh' >>/var/log/deals-backup.log 2>&1
EOF
  else
    cat >>"${tmp}" <<EOF
# deals-sqlite-backup (deploy.sh --install-backup-cron; daily 03:15 UTC)
15 3 * * * cd ${APP_DIR} && DATABASE_URL=${db_url} BACKUP_DIR=${backup_dir} ./scripts/backup-sqlite.sh >>/var/log/deals-backup.log 2>&1
# deals-backup-freshness (deploy.sh --install-backup-cron; daily 03:45 UTC)
45 3 * * * cd ${APP_DIR} && BACKUP_DIR=${backup_dir} MAX_AGE_HOURS=26 ./scripts/verify_backup_freshness.sh >>/var/log/deals-backup.log 2>&1
EOF
  fi
  if ! crontab "${tmp}"; then
    echo "ERROR: crontab install failed."
    rm -f "${tmp}"
    exit 1
  fi
  rm -f "${tmp}"

  echo "  Installed (idempotent) crontab entries:"
  crontab -l | grep -e 'deals-sqlite-backup' -e 'deals-backup-freshness' -e 'backup-sqlite.sh' -e 'verify_backup_freshness.sh' | sed 's/^/    /'

  echo ""
  if [ "${use_exec_variant}" -eq 1 ]; then
    echo "  Offsite copy (owner-ops — not installed automatically; named-volume deploys"
    echo "  must read /app/data/backups, e.g. 'docker compose exec deals ls /app/data/backups'):"
  else
    echo "  Offsite copy (owner-ops — not installed automatically):"
  fi
  echo "    rclone config   # remote 'deals-backup' → S3/B2/Drive, then:"
  echo "    rclone copy ${backup_dir} deals-backup:deals --log-file=/var/log/rclone-deals.log"
  echo "    crontab -e      # e.g. daily 03:30 UTC:"
  echo "    # 30 3 * * * rclone copy ${backup_dir} deals-backup:deals --log-file=/var/log/rclone-deals.log 2>&1"
  echo "  Monthly restore drill + date tracking: see docs/ops/backup-restore.md"
}

# Install repo nginx config → /etc/nginx/sites-available/deals (every deploy)
# Source of truth: ${APP_DIR}/nginx/deals.conf or deals.ssl.conf
install_nginx_from_repo() {
  local dest="/etc/nginx/sites-available/${APP_NAME}"
  local enabled="/etc/nginx/sites-enabled/${APP_NAME}"
  local http_src="${APP_DIR}/nginx/deals.conf"
  local ssl_src="${APP_DIR}/nginx/deals.ssl.conf"
  local tmp
  tmp="$(mktemp)"

  if [ ! -f "${http_src}" ]; then
    echo "  Nginx: no ${http_src} in repo — skipping"
    return 0
  fi

  echo "Installing Nginx site from repo → ${dest} (port ${APP_PORT})"

  # Prefer SSL template when Let's Encrypt certs already exist
  if [ -f "/etc/letsencrypt/live/${DOMAIN}/fullchain.pem" ] && [ -f "${ssl_src}" ]; then
    echo "  Using SSL template (certs found for ${DOMAIN})"
    sed -e "s/__DOMAIN__/${DOMAIN}/g" -e "s/__APP_PORT__/${APP_PORT}/g" "${ssl_src}" >"${tmp}"
    # Drop ssl_dhparam line if file missing (avoids nginx -t failure)
    if [ ! -f /etc/letsencrypt/ssl-dhparams.pem ]; then
      sed -i '/ssl_dhparam/d' "${tmp}"
    fi
    if [ ! -f /etc/letsencrypt/options-ssl-nginx.conf ]; then
      sed -i '/options-ssl-nginx.conf/d' "${tmp}"
    fi
  else
    echo "  Using HTTP template"
    sed -e "s/__DOMAIN__/${DOMAIN}/g" -e "s/__APP_PORT__/${APP_PORT}/g" "${http_src}" >"${tmp}"
  fi

  if ! as_root cp "${tmp}" "${dest}"; then
    echo "  WARNING: cannot write ${dest} (need root or passwordless sudo)."
    echo "  Install once: sudo cp ${tmp} ${dest} && sudo ln -sfn ${dest} ${enabled} && sudo nginx -t && sudo systemctl reload nginx"
    echo "  Or allow madhu: echo '${DEPLOY_USER} ALL=(root) NOPASSWD: /usr/sbin/nginx, /bin/systemctl reload nginx, /bin/cp, /bin/ln' | sudo tee /etc/sudoers.d/deals-nginx"
    rm -f "${tmp}"
    return 0
  fi
  rm -f "${tmp}"

  as_root ln -sfn "${dest}" "${enabled}" || true
  as_root mkdir -p /var/www/html || true

  # Install repo Cloudflare real-IP conf.d snippets → /etc/nginx/conf.d/.
  # Required by the `include conf.d/00-cloudflare-real-ip.conf;` in deals.*.conf;
  # without it nginx -t fails ("conf.d/00-cloudflare-real-ip.conf" not found).
  if [ -d "${APP_DIR}/nginx/conf.d" ]; then
    as_root mkdir -p /etc/nginx/conf.d || true
    for snippet in "${APP_DIR}/nginx/conf.d"/*.conf; do
      [ -f "${snippet}" ] || continue
      as_root cp "${snippet}" /etc/nginx/conf.d/ || true
    done
  fi

  if as_root nginx -t; then
    as_root systemctl reload nginx || as_root service nginx reload || true
    echo "  Nginx reloaded with git config for ${DOMAIN} → 127.0.0.1:${APP_PORT}"
  else
    echo "  ERROR: nginx -t failed after installing ${dest}"
    return 1
  fi
}

configure_nginx() {
  echo "Configuring Nginx reverse proxy for ${DOMAIN}..."
  apt-get update -y
  apt-get install -y nginx
  install_nginx_from_repo
  systemctl enable --now nginx
}

pull_or_clone() {
  # Avoid "dubious ownership" when directory was created by another user
  git config --global --add safe.directory "${APP_DIR}" 2>/dev/null || true

  # If root left root-owned files, git pull fails for madhu ("Permission denied")
  if [ ! -w "${APP_DIR}/.git" ] || [ ! -w "${APP_DIR}" ]; then
    echo "WARNING: ${APP_DIR} not fully writable by $(whoami)."
    echo "  As root run: chown -R ${DEPLOY_USER}:${DEPLOY_USER} ${APP_DIR}"
  fi

  if [ -d "${APP_DIR}/.git" ]; then
    echo "Updating repository (hard reset to origin/${BRANCH})..."
    if ! git -C "${APP_DIR}" fetch origin; then
      echo "git fetch failed — check ownership of ${APP_DIR} (must be ${DEPLOY_USER})"
      exit 1
    fi
    git -C "${APP_DIR}" checkout "${BRANCH}"
    # Server must match GitHub; discard local edits (preserve .env via clean -e)
    if ! git -C "${APP_DIR}" reset --hard "origin/${BRANCH}"; then
      echo "git reset failed — often root-owned files under ${APP_DIR}."
      echo "  Fix once as root: chown -R ${DEPLOY_USER}:${DEPLOY_USER} ${APP_DIR}"
      exit 1
    fi
    git -C "${APP_DIR}" clean -fd -e .env -e data -e 'prisma/*.db' -e 'prisma/*.db-journal' || true
  else
    mkdir -p "$(dirname "${APP_DIR}")"
    if [ -d "${APP_DIR}" ] && [ -n "$(ls -A "${APP_DIR}" 2>/dev/null | grep -v '^\.env$' || true)" ]; then
      echo "Cloning into temp then merging..."
      TMP="$(mktemp -d)"
      git clone --branch "${BRANCH}" "${REPO_URL}" "${TMP}"
      if [ -f "${APP_DIR}/.env" ]; then
        cp "${APP_DIR}/.env" "${TMP}/.env"
      fi
      # Preserve data if any
      rm -rf "${APP_DIR}"
      mv "${TMP}" "${APP_DIR}"
    else
      echo "Cloning ${REPO_URL}..."
      git clone --branch "${BRANCH}" "${REPO_URL}" "${APP_DIR}"
    fi
  fi
}

compose_up() {
  cd "${APP_DIR}"
  echo "Building and starting containers..."

  # Near-zero downtime: do NOT `docker compose down` first — the running
  # container keeps serving while the new image builds, then compose
  # recreates it in place (--force-recreate). `--wait` holds the deploy
  # until the service passes its healthcheck (compose healthcheck below).
  # Fallback for a stuck/foreign container still holding the host port:
  # stop it so compose can bind the port again (the compose-managed
  # deals-app container is skipped — compose handles its own recreation).
  if command -v docker >/dev/null 2>&1; then
    for id in $(docker ps -q --filter "publish=${APP_PORT}" 2>/dev/null || true); do
      if [ "$(docker inspect -f '{{.Name}}' "${id}" 2>/dev/null || true)" = "/deals-app" ]; then
        continue
      fi
      echo "  Stopping stale container on host port ${APP_PORT}: ${id}"
      docker stop "${id}" >/dev/null 2>&1 || true
      docker rm "${id}" >/dev/null 2>&1 || true
    done
  fi

  docker compose pull 2>/dev/null || true
  docker compose up -d --build --remove-orphans --force-recreate --wait

  # Flip the first-time seed flag (see flip_seed_flag): no sleep needed —
  # compose baked RUN_SEED into the container at create time, so the flip only
  # affects future recreates, and this update path never sets RUN_SEED=true.
  flip_seed_flag

  echo "Container status:"
  docker compose ps
  docker compose logs --tail=30 || true
}

fix_ownership() {
  if [ "$(id -u)" -eq 0 ] && id "${DEPLOY_USER}" >/dev/null 2>&1; then
    chown -R "${DEPLOY_USER}:${DEPLOY_USER}" "${APP_DIR}"
    echo "Ownership of ${APP_DIR} → ${DEPLOY_USER}"
  fi
}

# ---------------------------------------------------------------------------
# Backup cron install (non-root: run as madhu — never requires root)
# ---------------------------------------------------------------------------
if [ "${MODE}" = "install-backup-cron" ]; then
  echo "    Running backup-cron install as $(whoami) for ${APP_DIR}..."
  install_backup_cron

  echo ""
  echo "=== Backup cron install complete ==="
  echo "  Crontab: crontab -l | grep deals-"
  echo "  Logs:    tail -f /var/log/deals-backup.log"
  echo "  Offsite: rclone copy (see output above + docs/ops/backup-restore.md)"
  exit 0
fi

# ---------------------------------------------------------------------------
# Update path (non-root: run as madhu — NEVER requires root)
# ---------------------------------------------------------------------------
if [ "${MODE}" = "update" ]; then
  echo "    Running non-root update as $(whoami)..."
  need_docker

  if [ ! -d "${APP_DIR}/.git" ]; then
    echo "App not found at ${APP_DIR}."
    exit 1
  fi

  if [ ! -w "${APP_DIR}" ]; then
    echo "No write access to ${APP_DIR} as $(whoami)."
    echo "As root once: chown -R ${DEPLOY_USER}:${DEPLOY_USER} ${APP_DIR}"
    exit 1
  fi

  # Repo may already be pulled by CI; pull again is fine / no-op if up to date
  pull_or_clone
  ensure_env
  chmod +x "${APP_DIR}/deploy.sh" "${APP_DIR}/docker/entrypoint.sh" 2>/dev/null || true
  compose_up
  # Copy nginx/*.conf from this repo into sites-available on every deploy
  install_nginx_from_repo

  echo ""
  echo "=== Update complete ==="
  echo "  App:  https://${DOMAIN}  (upstream 127.0.0.1:${APP_PORT})"
  echo "  Logs: cd ${APP_DIR} && docker compose logs -f"
  exit 0
fi

# ---------------------------------------------------------------------------
# Full bootstrap (root once) — prepares madhu + /home/madhu/deals
# ---------------------------------------------------------------------------
need_root

echo "1. Updating system packages..."
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get upgrade -y
apt-get install -y git curl ca-certificates openssl ufw

echo "2. Installing Docker..."
install_docker

echo "3. Ensuring deploy user (${DEPLOY_USER})..."
ensure_deploy_user

echo "4. Application directory ${APP_DIR}..."
# Ensure home exists
if [ ! -d "/home/${DEPLOY_USER}" ]; then
  mkdir -p "/home/${DEPLOY_USER}"
  chown "${DEPLOY_USER}:${DEPLOY_USER}" "/home/${DEPLOY_USER}"
fi
pull_or_clone
chmod +x "${APP_DIR}/deploy.sh" "${APP_DIR}/docker/entrypoint.sh" 2>/dev/null || true

echo "5. Environment file..."
ensure_env
fix_ownership

echo "6. Building and starting app (as ${DEPLOY_USER})..."
# Run compose as deploy user so containers are owned correctly
if [ "$(id -u)" -eq 0 ]; then
  su - "${DEPLOY_USER}" -c "cd '${APP_DIR}' && docker compose up -d --build --remove-orphans"
  # Flip first-time seed flag (see flip_seed_flag): the container baked
  # RUN_SEED=true at create time and seeds once; future restarts skip seeding.
  flip_seed_flag
else
  compose_up
fi

echo "7. Nginx reverse proxy..."
configure_nginx

echo "8. Firewall..."
if command -v ufw &>/dev/null; then
  ufw allow OpenSSH || true
  ufw allow 'Nginx Full' || true
  ufw --force enable || true
fi

fix_ownership

echo ""
echo "=== Deployment complete ==="
echo "  HTTP:  http://${DOMAIN}"
echo "  App:   ${APP_DIR} (owner: ${DEPLOY_USER})"
echo "  Admin: http://${DOMAIN}/admin"
echo "  Logs:  su - ${DEPLOY_USER} -c 'cd ${APP_DIR} && docker compose logs -f'"
echo ""
echo "  SSL:"
echo "    apt-get install -y certbot python3-certbot-nginx"
echo "    certbot --nginx -d ${DOMAIN} -d www.${DOMAIN}"
echo ""
echo "  GitHub Actions secrets:"
echo "    DEPLOY_USER=madhu"
echo "    DEPLOY_PATH=${APP_DIR}"
echo "    DEPLOY_HOST=<server-ip>"
echo "    DEPLOY_SSH_KEY=<private key for madhu>"
